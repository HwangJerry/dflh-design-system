#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const contractPath = path.join(root, 'design-system', 'contracts', 'component-contracts.json');
const outputPath = path.join(root, 'design-system', 'contracts', 'COMPONENT_CONTRACTS.md');
const checkOnly = process.argv.includes('--check');

const contracts = JSON.parse(fs.readFileSync(contractPath, 'utf8'));

function list(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return '- None declared';
  }
  return items.map((item) => `- \`${item}\``).join('\n');
}

function inlineList(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return 'None declared';
  }
  return items.map((item) => `\`${item}\``).join(', ');
}

function tokenUsageRows(requiredTokenUsage) {
  if (!requiredTokenUsage || typeof requiredTokenUsage !== 'object') {
    return '- None declared';
  }
  return Object.entries(requiredTokenUsage)
    .map(([slot, tokenRefs]) => `- ${slot}: ${inlineList(tokenRefs)}`)
    .join('\n');
}

function evidenceRows(implementationEvidence) {
  if (!implementationEvidence || typeof implementationEvidence !== 'object') {
    return '- Primitive contract: implementation evidence is enforced by consuming screen contracts.';
  }
  return Object.entries(implementationEvidence)
    .map(([platform, files]) => `- ${platform}: ${inlineList(files)}`)
    .join('\n');
}

const lines = [
  '# Design System Component Contracts',
  '',
  '<!-- Generated by design-system/scripts/generate-contract-docs.mjs. Do not edit by hand. -->',
  '',
  `- Version: \`${contracts.version}\``,
  `- Schema: \`${contracts.schema}\``,
  `- Scope: ${contracts.scope}`,
  '',
  '## Mandatory Surfaces',
  '',
  '### Shared Primitives',
  '',
  list(contracts.mandatoryPrimitiveContracts),
  '',
  '### Screens',
  '',
  list(contracts.mandatoryScreenContracts),
  '',
  '## Global Rules',
  '',
  list(contracts.globalRules),
  '',
  '## Violation Rules',
  '',
  ...(contracts.violationRules ?? []).flatMap((rule) => [
    `### \`${rule.id}\``,
    '',
    `- Severity: \`${rule.severity}\``,
    `- Applies to: ${inlineList(rule.appliesTo)}`,
    `- Description: ${rule.description}`,
    `- Machine detection: \`${Object.keys(rule.machineDetection ?? {}).join(', ') || 'not declared'}\``,
    '',
  ]),
  '## Evidence Requirements',
  '',
  ...Object.entries(contracts.contractEvidenceRequirements ?? {}).map(
    ([key, value]) => `- ${key}: ${value}`,
  ),
  '',
  '## Contract Matrix',
  '',
  '| Contract | Type | Platforms | States | Required Token Families |',
  '| --- | --- | --- | --- | --- |',
  ...(contracts.components ?? []).map((contract) => (
    `| \`${contract.name}\` | ${contract.contractType} | ${inlineList(contract.platforms)} | ${inlineList(contract.states)} | ${inlineList(contract.requiredTokenFamilies)} |`
  )),
  '',
  '## Contract Details',
  '',
  ...(contracts.components ?? []).flatMap((contract) => [
    `### \`${contract.name}\``,
    '',
    `- Type: \`${contract.contractType}\``,
    `- Mandatory: \`${contract.mandatory === true}\``,
    `- Platforms: ${inlineList(contract.platforms)}`,
    `- States: ${inlineList(contract.states)}`,
    contract.variants ? `- Variants: ${inlineList(contract.variants)}` : null,
    contract.requiredBlocks ? `- Required blocks: ${inlineList(contract.requiredBlocks)}` : null,
    '',
    'Required token families:',
    '',
    list(contract.requiredTokenFamilies),
    '',
    'Required token usage:',
    '',
    tokenUsageRows(contract.requiredTokenUsage),
    '',
    'Implementation evidence:',
    '',
    evidenceRows(contract.implementationEvidence),
    '',
    'Rules:',
    '',
    list(contract.rules),
    '',
  ].filter((line) => line !== null)),
];

const output = `${lines.join('\n')}\n`;

if (checkOnly) {
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (existing !== output) {
    console.error(`${path.relative(root, outputPath)} is stale. Run npm run generate-contract-docs.`);
    process.exit(1);
  }
  console.log(`${path.relative(root, outputPath)} is up to date.`);
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated ${path.relative(root, outputPath)}`);
}
